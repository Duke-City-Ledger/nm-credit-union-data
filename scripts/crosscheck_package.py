"""Compare our reading of the call reports with the package's, for the eight accounts both
carry, every New Mexico credit union, every quarter.

Two readers of the same zips: ours (src/nmcu/read.py) and ncua-data-analysis's ingest
and build. Any difference means one of them misread a file.

Needs the package's long Parquet first (about 10 minutes, a few GB in .cache/package/):
  uv run ncua-data --data .cache/package ingest
Then: uv run scripts/crosscheck_package.py   (after uv run nmcu build)
Writes docs/package-crosscheck.md and exits 1 on any difference.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from ncua_data.build import build as package_build

ROOT = Path(__file__).resolve().parent.parent
FIELDS = {  # package field -> our account
    "total_assets": "ACCT_010",
    "loans_and_leases_total": "ACCT_025B",
    "net_worth": "ACCT_997",
    "members": "ACCT_083",
    "loans_commercial_total": "ACCT_400T1",
    "delinquent_2m_plus": "ACCT_041B",
    "chargeoffs_ytd": "ACCT_550",
    "recoveries_ytd": "ACCT_551",
}


def main() -> int:
    ours = {}
    for f in sorted((ROOT / "out" / "quarters").glob("*.json")):
        doc = json.loads(f.read_text())
        for c in doc["credit_unions"]:
            ours[(doc["quarter"], int(c["cu_number"]))] = c["accounts"]

    con = package_build(ROOT / ".cache" / "package", ROOT / ".cache" / "package")
    cols = ", ".join(FIELDS)
    theirs = {(q, n): dict(zip(FIELDS, vals)) for q, n, *vals in
              con.execute(f"SELECT quarter, cu_number, {cols} FROM fact_call_report_curated").fetchall()}

    compared = differ = missing = null_vs_zero = 0
    lines = []
    for key, accounts in sorted(ours.items()):
        row = theirs.get(key)
        if row is None:
            missing += 1
            lines.append(f"- {key[0]} {key[1]}: not in the package's table")
            continue
        for field, account in FIELDS.items():
            compared += 1
            a, b = accounts[account], row[field]
            if a is None:
                # The package stores no row for a zero or a blank and reports 0 for both, so a
                # null of ours can't be checked against it. Counted, never passed as agreement.
                null_vs_zero += 1
                lines.append(f"- {key[0]} {key[1]} {account}: ours null, package {b} (not comparable)")
                continue
            if a != (b or 0):
                differ += 1
                lines.append(f"- {key[0]} {key[1]} {account}: ours {a}, package {b}")

    report = [
        "# Our reading against the package's",
        "",
        "Generated by `scripts/crosscheck_package.py`. Eight accounts both carry, every New Mexico credit union, "
        f"every quarter in `out/`: {compared:,} values compared, {differ} differ, {null_vs_zero} are null on our "
        f"side (not comparable: the package reports 0 for a blank), {missing} credit-union quarters missing from "
        "the package's table. A 0 of ours against no row in the package agrees: the package keeps non-zero values only.",
        "",
        *(lines or ["No differences."]),
    ]
    (ROOT / "docs" / "package-crosscheck.md").write_text("\n".join(report) + "\n")
    print(f"{compared} compared, {differ} differ, {null_vs_zero} null on our side, {missing} missing")
    return 1 if differ or missing or null_vs_zero else 0


if __name__ == "__main__":
    sys.exit(main())
