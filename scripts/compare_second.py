"""Compare the engine's output with the independent second calculation (second/).

second/second.py was written blind: from the spec, data/dictionary.json and NCUA's documents
only, by a different model, without the engine's code. Every figure and every peer statistic
is compared, every quarter. Writes docs/second-calculation.md and exits 1 on any difference.

Run: uv run nmcu build && (cd second && python3 second.py) && uv run scripts/compare_second.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SECOND = ROOT / "second" / "out"


def num(text: str):
    return None if text in ("", None) else float(text)


def main() -> int:
    engine = {(r["quarter"], r["cu_number"], r["measure"], r["part"]): num(r["value"])
              for r in csv.DictReader(open(ROOT / "out" / "credit-unions.csv"))}
    second = {(r["quarter"], r["cu_number"], r["measure"], r["part"] or ""): num(r["value"])
              for r in csv.DictReader(open(SECOND / "measures.csv"))}

    engine_peers = {}
    for f in sorted((ROOT / "out" / "quarters").glob("*.json")):
        doc = json.loads(f.read_text())
        for c in doc["credit_unions"]:
            for m, p in c["peers"].items():
                engine_peers[(doc["quarter"], c["cu_number"], m)] = (p["n_others"], p["median"], p["p25"], p["p75"])
    second_peers = {(r["quarter"], r["cu_number"], r["measure"]):
                    (int(r["n_others"]), num(r["median"]), num(r["p25"]), num(r["p75"]))
                    for r in csv.DictReader(open(SECOND / "peers.csv"))}

    lines = []
    for name, a, b in (("figure", engine, second), ("peer comparison", engine_peers, second_peers)):
        for k in sorted(set(a) - set(b)):
            lines.append(f"- {name} only in the engine: {' '.join(k)}")
        for k in sorted(set(b) - set(a)):
            lines.append(f"- {name} only in the second calculation: {' '.join(k)}")
        for k in sorted(set(a) & set(b)):
            if a[k] != b[k]:
                lines.append(f"- {name} {' '.join(k)}: engine {a[k]}, second {b[k]}")
    report = [
        "# The engine against the independent second calculation",
        "",
        "Generated by `scripts/compare_second.py`. The second calculation (`second/`) was written blind, by a",
        "different model, from the spec, the dictionary and NCUA's documents only.",
        "",
        f"{len(engine):,} figures and {len(engine_peers):,} peer comparisons in the engine; "
        f"{len(second):,} and {len(second_peers):,} in the second calculation; {len(lines)} differences.",
        "",
        *(lines[:500] or ["No differences."]),
    ]
    (ROOT / "docs" / "second-calculation.md").write_text("\n".join(report) + "\n")
    print(f"{len(engine)} figures, {len(engine_peers)} peer comparisons, {len(lines)} differences")
    return 1 if lines else 0


if __name__ == "__main__":
    sys.exit(main())
